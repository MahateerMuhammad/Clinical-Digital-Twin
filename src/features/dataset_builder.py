#: Prepended to `reports/feature_engineering_report.md`.
#:
#: That report documents *automated selection* — what was dropped for missingness,
#: variance or correlation — and by construction it says nothing about why any
#: feature was designed. It therefore contained no citation of any kind, which for a
#: clinical project is the least defensible gap in the documentation: a reviewer
#: asking "why shock index?" found only the line of pandas that computes it.
#:
#: Kept as a literal rather than derived, because these are editorial judgements about
#: prior work and there is nothing in the repo to derive them from. It is the one
#: place in this file where a hand-maintained block is the honest choice — so it is
#: written to be checkable: every claim names the feature or module it justifies.
CLINICAL_RATIONALE = """## Clinical Rationale & Literature

This report is generated by the automated selection pass, which drops features for
missingness, zero variance and collinearity. Those are statistical decisions and are
listed below. This section covers the prior question the selector cannot answer —
why the candidate features exist at all — and is the reference for anyone auditing
the clinical validity of the feature space.

### Derived physiological features

| Feature | Definition | Basis |
| :--- | :--- | :--- |
| `ed_triage_shock_index` | HR ÷ SBP | Allgöwer & Burri, *Dtsch Med Wochenschr* 1967, as the original description; re-validated for acute circulatory failure by Rady et al., *Resuscitation* 1992 and *Ann Emerg Med* 1994. Values above ~0.9 carry mortality signal that neither HR nor SBP shows alone, which is the reason for computing the ratio rather than trusting the model to find it. |
| `ed_triage_pulse_pressure` | SBP − DBP | Narrow pulse pressure indicates reduced stroke volume before hypotension appears; standard in early shock recognition. Non-positive values are set NaN in `src/features/emergency.py` — they are cuff artifacts, not measurements. |
| `pre_admission_charlson_index` | Weighted comorbidity burden from *prior* stays only | Charlson et al., *J Chronic Dis* 1987; ICD-9/10 coding algorithm from Quan et al., *Med Care* 2005. Computed from prior admissions rather than the index stay, because index-stay diagnoses are coded at discharge and are outcome-contaminated. |
| `prior_admissions_{30,90,365}d`, `prior_cumulative_los_days` | Utilisation history, strictly `dischtime < index admittime` | Prior utilisation is the strongest non-clinical readmission predictor in the validated indices — LACE (van Walraven et al., *CMAJ* 2010) and HOSPITAL (Donzé et al., *JAMA Intern Med* 2013) both weight it heavily. |

### Windowing and observation discipline

- **24-hour observation window.** Ward early-warning models are conventionally built
  from an early fixed window so the prediction precedes the clinical response;
  Churpek et al., *Am J Respir Crit Care Med* 2014 is the reference multicentre
  development of this design on ward patients.
- **Landmark design for Phase 5.** Fixing a landmark and admitting only patients
  still at risk is the standard correction for immortal-time bias — Anderson et al.,
  *J Clin Oncol* 1983, with the modern treatment in Dafni, *Circ Cardiovasc Qual
  Outcomes* 2011. Phase 5 was rebuilt to this design after the case-control version
  allowed feature windows to reach past the event.
- **Physiological range filtering.** `VITAL_RANGES` in `src/utils/validation.py`
  blanks out-of-range values to NaN rather than clamping them to the boundary.
  Clamping fabricates a measurement at exactly the threshold; blanking records that
  nothing usable was observed.

### Why missingness itself is treated as dangerous

The exclusion lists in `src/features/leakage_filters.py` remove `*_count`,
`*_abnormal_count` and `*_missing_ratio` families. The justification is Agniel,
Kohane & Weber, *BMJ* 2018, which demonstrates that in EHR data the *presence* of a
measurement encodes clinician concern and healthcare-process structure, often
predicting outcomes better than the measured value. This is not a theoretical
concern here: Phase 5's original model ranked `lab_unique_items_24h` and
`lab_total_count_24h` first and third by SHAP, i.e. it was reading how much testing
was ordered rather than the patient's state.

### Evaluation choices

- **AUPRC alongside AUROC**, and enrichment over base rate rather than raw AUPRC when
  base rates differ — Saito & Rehmsmeier, *PLoS One* 2015.
- **Isotonic calibration** fitted on the validation split — Zadrozny & Elkan, *KDD*
  2002; Niculescu-Mizil & Caruana, *ICML* 2005. Necessary here because
  `scale_pos_weight` distorts raw scores badly at the ~2% base rates in Phases 1
  and 5.
- **Brier score** as the calibration metric — Brier, *Monthly Weather Review* 1950.

### Data source

MIMIC-IV (Johnson et al., *Scientific Data* 2023) and the MIMIC-IV-ED module
(PhysioNet). ED coverage of this cohort is 37.1%; see
`reports/tables/ed_feature_coverage.md`.

> [!NOTE]
> Citations are given as author/journal/year without DOIs, deliberately. Every entry
> above is a well-established reference the authors could verify directly; inventing
> identifiers to look more rigorous is the failure mode this project has spent its
> audits removing.

"""


class DatasetBuilder:
    """Produce patient, admission, ICU, time-series, notes, and similarity datasets."""

    def __init__(self) -> None:
        self.cfg = CFG
        self.merger = TableMerger()
        self.processed_dir = Path(self.cfg.resolve(self.cfg.paths.processed))

    def build_all(
        self,
        tables: Dict[str, pd.DataFrame],
        features: Dict[str, pd.DataFrame],
        apply_feature_selection: bool = True,
    ) -> Dict[str, pd.DataFrame]:
        """Build and save all target datasets."""
        admissions = tables.get("admissions", pd.DataFrame())
        patients = tables.get("patients", pd.DataFrame())
        icustays = tables.get("icustays", pd.DataFrame())

        if admissions.empty:
            raise ValueError("admissions table required for dataset creation")

        admissions = self.merger.add_icu_flags(admissions, icustays)

        hadm_features = {
            k: v for k, v in features.items()
            if v is not None and not v.empty and "hadm_id" in v.columns
        }

        admission_df = self.merger.merge_admission_level(admissions, patients, hadm_features)
        patient_df = self.merger.merge_patient_level(admission_df)

        icu_features = {}
        if "vitals" in features:
            icu_features["vitals"] = features["vitals"]
        if "fluids" in features:
            icu_features["fluids"] = features["fluids"]
        icu_df = self.merger.merge_icu_level(icustays, admissions, icu_features)

        ts_df = self.merger.build_time_series(
            admissions,
            labs=tables.get("labevents"),
            vitals=features.get("vitals"),
            meds=tables.get("prescriptions"),
        )

        notes_df = features.get("notes", pd.DataFrame())
        similarity_df = self.merger.build_similarity_dataset(
            admission_df, features.get("diagnosis"),
        )

        datasets = {
            "patient_level": patient_df,
            "admission_level": admission_df,
            "icu_level": icu_df,
            "time_series": ts_df,
            "clinical_notes": notes_df,
            "similarity": similarity_df,
        }

        fs_report: Optional[FeatureSelectionReport] = None
        if apply_feature_selection and not admission_df.empty:
            selected, fs_report = prepare_features(admission_df)
            datasets["admission_level_selected"] = selected
            self._save_feature_selection_reports(selected, fs_report)

        self._save_datasets(datasets)
        self._generate_documentation(datasets, fs_report)
        return datasets

    def _save_datasets(self, datasets: Dict[str, pd.DataFrame]) -> None:
        for name, df in datasets.items():
            if df is not None and not df.empty:
                path = self.processed_dir / f"{name}.parquet"
                save_parquet(df, path)
                log.info("Saved dataset '%s' → %s (%d rows)", name, path.name, len(df))

    def _save_feature_selection_reports(
        self,
        df: pd.DataFrame,
        report: FeatureSelectionReport,
    ) -> None:
        tables_dir = Path(self.cfg.resolve(self.cfg.paths.tables))
        tables_dir.mkdir(parents=True, exist_ok=True)

        save_parquet(generate_missing_report(df), tables_dir / "feature_missing_report.parquet")
        generate_correlation_report(df, str(tables_dir / "feature_correlation_report.parquet"))

        with open(self.cfg.resolve("reports/feature_engineering_report.md"), "w", encoding="utf-8") as fh:
            fh.write("# Feature Engineering Report\n\n")
            fh.write(f"Generated: {datetime.utcnow().isoformat()}Z\n\n")
            fh.write(CLINICAL_RATIONALE)
            fh.write("## Feature Selection Summary\n\n")
            for k, v in report.to_dict().items():
                if k not in ["dropped_features", "kept_features", "highly_correlated_pairs"]:
                    fh.write(f"- **{k}**: {v}\n")
            
            fh.write("\n## Dropped Features (Categorized by Reason)\n\n")
            fh.write("### Genuine Clinical Missingness (> Threshold)\n")
            fh.write("*(Note: In prior runs, all vitals/labs were dropped here due to the 1.5M row-cap bug. These are now true clinical drops.)*\n")
            for feat in sorted(report.high_missing)[:50]:
                fh.write(f"- {feat}\n")
            if len(report.high_missing) > 50: fh.write(f"- _... and {len(report.high_missing)-50} more_\n")
            
            fh.write("\n### Constant / Zero Variance\n")
            for feat in sorted(report.constant_features + report.near_zero_variance)[:50]:
                fh.write(f"- {feat}\n")
            if len(report.constant_features + report.near_zero_variance) > 50: fh.write("- _... and more_\n")
            
            fh.write("\n### Duplicates / Highly Correlated\n")
            corr_drops = [p[1] for p in report.highly_correlated_pairs]
            for feat in sorted(report.duplicate_features + corr_drops)[:50]:
                fh.write(f"- {feat}\n")
            if len(report.duplicate_features + corr_drops) > 50: fh.write("- _... and more_\n")

    def _generate_documentation(
        self,
        datasets: Dict[str, pd.DataFrame],
        fs_report: Optional[FeatureSelectionReport],
    ) -> None:
        """Generate data dictionary and dataset summary."""
        records = []
        for name, df in datasets.items():
            if df is None or df.empty:
                continue
            for col in df.columns:
                records.append({
                    "dataset": name,
                    "feature": col,
                    "dtype": str(df[col].dtype),
                    "n_missing": int(df[col].isna().sum()),
                    "pct_missing": round(100 * df[col].isna().mean(), 2),
                    "n_unique": int(df[col].nunique(dropna=True)),
                    "example": str(df[col].dropna().iloc[0])[:80] if df[col].notna().any() else "",
                })

        dict_df = pd.DataFrame(records)
        dict_path = Path(self.cfg.resolve("reports/tables/feature_dictionary.parquet"))
        save_parquet(dict_df, dict_path)

        summary = pd.DataFrame([
            {"dataset": k, "n_rows": len(v), "n_cols": v.shape[1]}
            for k, v in datasets.items() if v is not None and not v.empty
        ])
        save_parquet(summary, Path(self.cfg.resolve("reports/tables/dataset_summary.parquet")))

        with open(self.cfg.resolve("reports/data_dictionary.md"), "w", encoding="utf-8") as fh:
            fh.write("# Data Dictionary\n\n")
            fh.write(f"Generated: {datetime.utcnow().isoformat()}Z\n\n")
            fh.write("## Dataset Summary\n\n")
            fh.write(df_to_markdown(summary))
            fh.write(self._staged_features_section(datasets))
            fh.write("\n\n## Feature Dictionary (sample)\n\n")
            fh.write(df_to_markdown(dict_df.head(200)))

        log.info("Documentation saved to reports/")

    def _staged_features_section(self, datasets: Dict[str, pd.DataFrame]) -> str:
        """
        Document feature sets that are built but reach no dataset.

        This dictionary describes the datasets, so a feature set that exists on disk
        and is never merged is invisible to it — which is how 66 emergency-department
        features came to be built, tested and leakage-screened while appearing in no
        documentation at all. An audit found them by reading the source tree.

        Derived by comparing `data/interim/features/*.parquet` against the columns
        actually present downstream, so a set disappears from this section on the day
        it is adopted. Nothing here is hand-maintained: a hand-written "not yet used"
        note is exactly the kind of claim that survives the thing it describes.
        """
        feature_dir = Path(self.cfg.resolve(self.cfg.paths.interim)) / "features"
        if not feature_dir.exists():
            return ""

        downstream = set()
        for frame in datasets.values():
            if frame is not None and not frame.empty:
                downstream.update(frame.columns)

        rows = []
        for path in sorted(feature_dir.glob("*_features.parquet")):
            try:
                columns = [f.name for f in pq.ParquetFile(path).schema_arrow]
                n_rows = pq.ParquetFile(path).metadata.num_rows
            except Exception:                      # unreadable artifact, not our concern
                continue
            payload = [c for c in columns if c not in ("hadm_id", "subject_id", "stay_id")]
            if not payload or any(c in downstream for c in payload):
                continue                            # merged downstream: already documented
            rows.append({
                "feature set": path.stem.replace("_features", ""),
                "file": f"`{path.relative_to(Path(self.cfg.resolve('.')))}`",
                "rows": n_rows,
                "features": len(payload),
                "example columns": ", ".join(f"`{c}`" for c in payload[:3]),
            })

        if not rows:
            return ""

        return (
            "\n\n## Staged Feature Sets (built, not consumed)\n\n"
            "These are engineered and persisted but merge into no dataset above, so no\n"
            "trained model uses them. This section is derived by comparing the interim\n"
            "feature files against the dataset columns — a set listed here disappears\n"
            "from it automatically once adopted.\n\n"
            + df_to_markdown(pd.DataFrame(rows)))
